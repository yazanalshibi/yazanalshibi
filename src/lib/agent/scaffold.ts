function apiFiles(name: string, idea: string): ScaffoldFile[] {
  return [
    {
      path: "package.json",
      contents: JSON.stringify(
        {
          name,
          version: "0.1.0",
          private: true,
          type: "module",
          scripts: {
            dev: "tsx watch src/server.ts",
            start: "tsx src/server.ts",
          },
          dependencies: {},
          devDependencies: { tsx: "^4.0.0", typescript: "^5.0.0", "@types/node": "^20.0.0" },
        },
        null,
        2,
      ),
    },
    {
      path: "README.md",
      contents: `# ${name}

API MVP for: ${idea}

Endpoints:
- GET /health
- POST /v1/run
`,
    },
    {
      path: "src/server.ts",
      contents: `import { createServer } from "node:http";

const port = Number(process.env.PORT || 8787);

const server = createServer(async (req, res) => {
  const url = new URL(req.url || "/", \`http://\${req.headers.host}\`);

  if (req.method === "GET" && url.pathname === "/health") {
    res.writeHead(200, { "content-type": "application/json" });
    res.end(JSON.stringify({ ok: true, service: "${name}" }));
    return;
  }

  if (req.method === "POST" && url.pathname === "/v1/run") {
    const chunks: Buffer[] = [];
    for await (const chunk of req) chunks.push(chunk as Buffer);
    const body = Buffer.concat(chunks).toString("utf8");
    let input = body;
    try {
      input = JSON.parse(body).input ?? body;
    } catch {
      /* raw body */
    }
    res.writeHead(200, { "content-type": "application/json" });
    res.end(
      JSON.stringify({
        ok: true,
        idea: ${JSON.stringify(idea)},
        input,
        result: "Replace this with your domain logic.",
      }),
    );
    return;
  }

  res.writeHead(404, { "content-type": "application/json" });
  res.end(JSON.stringify({ error: "not_found" }));
});

server.listen(port, () => {
  console.log(\`${name} listening on http://localhost:\${port}\`);
});
`,
    },
  ];
}

function cliFiles(name: string, idea: string): ScaffoldFile[] {
  return [
    {
      path: "package.json",
      contents: JSON.stringify(
        {
          name,
          version: "0.1.0",
          type: "module",
          bin: { [name]: "./bin/run.mjs" },
          scripts: { start: "node ./bin/run.mjs" },
        },
        null,
        2,
      ),
    },
    {
      path: "README.md",
      contents: `# ${name}

CLI MVP for: ${idea}

\`\`\`bash
node bin/run.mjs "your input"
\`\`\`
`,
    },
    {
      path: "bin/run.mjs",
      contents: `#!/usr/bin/env node
const input = process.argv.slice(2).join(" ").trim();
const idea = ${JSON.stringify(idea)};

if (!input) {
  console.log(\`${name} — \${idea}\`);
  console.log("Usage: node bin/run.mjs <input>");
  process.exit(0);
}

console.log(JSON.stringify({
  tool: ${JSON.stringify(name)},
  input,
  next: \`Ship the smallest demo for: \${input}\`,
}, null, 2));
`,
    },
  ];
}
