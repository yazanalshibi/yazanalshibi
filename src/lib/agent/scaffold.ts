import type { ScaffoldRequest, ScaffoldTemplateId } from "./types";

export type ScaffoldFile = {
  path: string;
  contents: string;
};

function packageName(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-|-$/g, "") || "mvp-project";
}

export function listTemplates(): { id: ScaffoldTemplateId; label: string; blurb: string }[] {
  return [
    {
      id: "web-saas",
      label: "Web SaaS slice",
      blurb: "Next.js app with a single authenticated-feeling core loop.",
    },
    {
      id: "landing-waitlist",
      label: "Landing + waitlist",
      blurb: "Brand-first landing page and email capture endpoint.",
    },
    {
      id: "api-service",
      label: "API service",
      blurb: "Minimal API with health check and one domain route.",
    },
    {
      id: "cli-tool",
      label: "CLI tool",
      blurb: "TypeScript CLI that runs one valuable command.",
    },
  ];
}

export function generateScaffold(req: ScaffoldRequest): ScaffoldFile[] {
  const name = packageName(req.name);
  const idea = req.idea.trim() || "Ship the smallest useful loop.";

  switch (req.template) {
    case "landing-waitlist":
      return landingFiles(name, idea);
    case "api-service":
      return apiFiles(name, idea);
    case "cli-tool":
      return cliFiles(name, idea);
    default:
      return webSaasFiles(name, idea);
  }
}

